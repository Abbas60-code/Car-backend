export async function seedAll() {
  if (!MONGO_URI) {
    console.error('❌ MONGO_URI not found in environment variables (.env)');
    process.exit(1);
  }

  console.log('🔌 Connecting to MongoDB Atlas...');
  await mongoose.connect(MONGO_URI);
  console.log('✅ Connected to MongoDB Atlas successfully!');

  // 1. Seed or Update Admin User
  const existingAdmin = await User.findOne({ email: ADMIN_EMAIL });
  if (existingAdmin) {
    existingAdmin.role = 'admin';
    await existingAdmin.save();
    console.log(`👤 Admin verified: ${ADMIN_EMAIL} (role: admin)`);
  } else {
    const hashedPassword = await bcrypt.hash(ADMIN_PASSWORD, 10);
    await User.create({
      name: ADMIN_NAME,
      email: ADMIN_EMAIL,
      password: hashedPassword,
      role: 'admin',
    });
    console.log(`👤 Admin created: ${ADMIN_EMAIL} / ${ADMIN_PASSWORD}`);
  }

  // 2. Clear previous cars and insert 50 fresh cars (10 per category)
  console.log('🚗 Clearing existing cars collection to ensure clean seeding...');
  await Car.deleteMany({});

  console.log(`📦 Inserting ${seedCarsData.length} cars into database...`);
  const insertedCars = await Car.insertMany(seedCarsData);
  console.log(`✅ Successfully seeded ${insertedCars.length} cars!`);

  // 3. Print breakdown by category
  const categories = ['Sports', 'Electric', 'Luxury', 'SUV', 'Executive'];
  console.log('\n📊 Category Breakdown:');
  for (const cat of categories) {
    const count = await Car.countDocuments({ type: cat });
    console.log(`   - ${cat.padEnd(12)}: ${count} cars`);
  }

  await mongoose.disconnect();
  console.log('\n✨ Database seeding completed successfully!');
}

// Run directly if invoked via node seedCars.js
if (process.argv[1]?.endsWith('seedCars.js') || process.argv[1]?.includes('seedCars')) {
  seedAll().catch((err) => {
    console.error('❌ Seeding error:', err);
    process.exit(1);
  });
}
